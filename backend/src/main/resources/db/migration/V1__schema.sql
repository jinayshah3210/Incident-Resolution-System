-- ResolveIT schema, version 1.
-- Portable SQL: runs on PostgreSQL 15+ (runtime) and on H2 in PostgreSQL mode (automated tests).
-- Hibernate runs with ddl-auto=validate, so every entity mapping must match these tables.

-- ---------------------------------------------------------------- users (JOINED inheritance)
CREATE TABLE users (
    id                    VARCHAR(20)  PRIMARY KEY,
    role                  VARCHAR(20)  NOT NULL,
    name                  VARCHAR(120) NOT NULL,
    email                 VARCHAR(160) NOT NULL,
    password_hash         VARCHAR(100) NOT NULL,
    department            VARCHAR(120),
    phone                 VARCHAR(40),
    active                BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_login_attempts INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMP WITH TIME ZONE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('EMPLOYEE', 'TECHNICIAN', 'ADMIN'))
);

CREATE TABLE employees (
    user_id   VARCHAR(20) PRIMARY KEY REFERENCES users (id),
    join_date DATE
);

CREATE TABLE technicians (
    user_id          VARCHAR(20) PRIMARY KEY REFERENCES users (id),
    max_workload     INTEGER NOT NULL,
    experience_years INTEGER NOT NULL DEFAULT 1,
    team_lead        BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_technician_workload CHECK (max_workload BETWEEN 1 AND 50)
);

CREATE TABLE technician_skills (
    technician_id VARCHAR(20) NOT NULL REFERENCES technicians (user_id),
    skill         VARCHAR(60) NOT NULL,
    PRIMARY KEY (technician_id, skill)
);

CREATE TABLE administrators (
    user_id     VARCHAR(20) PRIMARY KEY REFERENCES users (id),
    admin_level VARCHAR(20) NOT NULL
);

-- ---------------------------------------------------------------- catalog
CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(60)  NOT NULL,
    description VARCHAR(300),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_categories_name UNIQUE (name)
);

CREATE TABLE category_keywords (
    category_id BIGINT      NOT NULL REFERENCES categories (id),
    keyword     VARCHAR(60) NOT NULL,
    weight      INTEGER     NOT NULL DEFAULT 1,
    PRIMARY KEY (category_id, keyword)
);

CREATE TABLE services (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    description VARCHAR(600) NOT NULL,
    category    VARCHAR(60)  NOT NULL,
    criticality INTEGER      NOT NULL,
    keywords    VARCHAR(500),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_services_name UNIQUE (name),
    CONSTRAINT ck_services_criticality CHECK (criticality BETWEEN 1 AND 4)
);

CREATE TABLE service_technicians (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id    BIGINT      NOT NULL REFERENCES services (id),
    technician_id VARCHAR(20) NOT NULL REFERENCES users (id),
    CONSTRAINT uk_service_technician UNIQUE (service_id, technician_id)
);

-- ---------------------------------------------------------------- incidents (aggregate root)
CREATE TABLE incidents (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id                  VARCHAR(20)  NOT NULL,
    sequence_number            BIGINT       NOT NULL,
    title                      VARCHAR(120) NOT NULL,
    description                VARCHAR(2000) NOT NULL,
    reporter_id                VARCHAR(20)  NOT NULL REFERENCES users (id),
    reporter_name              VARCHAR(120),
    technician_id              VARCHAR(20)  REFERENCES users (id),
    technician_name            VARCHAR(120),
    category                   VARCHAR(60),
    classification_confidence  INTEGER      NOT NULL DEFAULT 0,
    service_name               VARCHAR(120),
    impact                     INTEGER      NOT NULL DEFAULT 1,
    urgency                    INTEGER      NOT NULL DEFAULT 1,
    criticality                INTEGER      NOT NULL DEFAULT 1,
    affected_users             INTEGER      NOT NULL DEFAULT 1,
    priority_score             INTEGER      NOT NULL DEFAULT 0,
    priority                   VARCHAR(4),
    priority_strategy          VARCHAR(30),
    status                     VARCHAR(20)  NOT NULL,
    created_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
    classified_at              TIMESTAMP WITH TIME ZONE,
    assigned_at                TIMESTAMP WITH TIME ZONE,
    acknowledged_at            TIMESTAMP WITH TIME ZONE,
    started_at                 TIMESTAMP WITH TIME ZONE,
    resolved_at                TIMESTAMP WITH TIME ZONE,
    verified_at                TIMESTAMP WITH TIME ZONE,
    closed_at                  TIMESTAMP WITH TIME ZONE,
    response_due_at            TIMESTAMP WITH TIME ZONE,
    resolution_due_at          TIMESTAMP WITH TIME ZONE,
    response_sla               VARCHAR(12)  NOT NULL DEFAULT 'ON_TRACK',
    resolution_sla             VARCHAR(12)  NOT NULL DEFAULT 'ON_TRACK',
    sla_status                 VARCHAR(12)  NOT NULL DEFAULT 'OK',
    escalation_level           INTEGER      NOT NULL DEFAULT 0,
    resolution_summary         VARCHAR(2000),
    root_cause                 VARCHAR(2000),
    resolution_steps           VARCHAR(4000),
    technician_approved        BOOLEAN      NOT NULL DEFAULT FALSE,
    employee_approved          BOOLEAN      NOT NULL DEFAULT FALSE,
    correlation_group          VARCHAR(20),
    duplicate_of               VARCHAR(20),
    version                    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_incidents_public_id UNIQUE (public_id),
    CONSTRAINT uk_incidents_sequence UNIQUE (sequence_number),
    CONSTRAINT ck_incidents_status CHECK (status IN ('NEW','CLASSIFIED','ASSIGNED','ACKNOWLEDGED','IN_PROGRESS','RESOLVED','VERIFIED','CLOSED')),
    CONSTRAINT ck_incidents_scales CHECK (impact BETWEEN 1 AND 4 AND urgency BETWEEN 1 AND 4 AND criticality BETWEEN 1 AND 4 AND affected_users BETWEEN 1 AND 4)
);
CREATE INDEX idx_incidents_status ON incidents (status);
CREATE INDEX idx_incidents_priority ON incidents (priority);
CREATE INDEX idx_incidents_reporter ON incidents (reporter_id);
CREATE INDEX idx_incidents_technician ON incidents (technician_id);
CREATE INDEX idx_incidents_created ON incidents (created_at);
CREATE INDEX idx_incidents_service ON incidents (service_name);
CREATE INDEX idx_incidents_correlation ON incidents (correlation_group);

CREATE TABLE incident_declines (
    incident_id   BIGINT      NOT NULL REFERENCES incidents (id),
    technician_id VARCHAR(20) NOT NULL,
    PRIMARY KEY (incident_id, technician_id)
);

CREATE TABLE incident_notes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT        NOT NULL REFERENCES incidents (id),
    author_id   VARCHAR(20)   NOT NULL,
    author_name VARCHAR(120),
    note_type   VARCHAR(30)   NOT NULL,
    content     VARCHAR(2000) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_notes_incident ON incident_notes (incident_id);

CREATE TABLE chat_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT        NOT NULL REFERENCES incidents (id),
    sender_id   VARCHAR(20)   NOT NULL,
    sender_name VARCHAR(120),
    content     VARCHAR(2000) NOT NULL,
    sent_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_chat_incident ON chat_messages (incident_id);

CREATE TABLE feedback (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT      NOT NULL REFERENCES incidents (id),
    employee_id VARCHAR(20) NOT NULL,
    rating      INTEGER     NOT NULL,
    comment     VARCHAR(1000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_feedback_incident UNIQUE (incident_id),
    CONSTRAINT ck_feedback_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE sla_violations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id    BIGINT      NOT NULL REFERENCES incidents (id),
    violation_type VARCHAR(12) NOT NULL,
    due_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    detected_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    delay_minutes  BIGINT      NOT NULL DEFAULT 0,
    technician_id  VARCHAR(20),
    dismissed      BOOLEAN     NOT NULL DEFAULT FALSE,
    dismissed_by   VARCHAR(20),
    CONSTRAINT uk_sla_violation UNIQUE (incident_id, violation_type)
);

CREATE TABLE escalations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT      NOT NULL REFERENCES incidents (id),
    level       INTEGER     NOT NULL,
    target_role VARCHAR(30) NOT NULL,
    target_user VARCHAR(20),
    reason      VARCHAR(300) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_escalation_level UNIQUE (incident_id, level)
);

-- ---------------------------------------------------------------- audit, notifications, settings
-- audit_events is append-only: the application exposes no update or delete path.
CREATE TABLE audit_events (
    id              VARCHAR(36)  PRIMARY KEY,
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    actor           VARCHAR(40)  NOT NULL,
    incident_id     VARCHAR(20)  NOT NULL,
    action          VARCHAR(60)  NOT NULL,
    detail          VARCHAR(4000),
    previous_status VARCHAR(20),
    new_status      VARCHAR(20)
);
CREATE INDEX idx_audit_incident ON audit_events (incident_id);
CREATE INDEX idx_audit_time ON audit_events (occurred_at);

CREATE TABLE notifications (
    id                VARCHAR(36)  PRIMARY KEY,
    user_id           VARCHAR(20)  NOT NULL,
    incident_id       VARCHAR(20),
    notification_type VARCHAR(40)  NOT NULL,
    title             VARCHAR(160) NOT NULL,
    message           VARCHAR(1000) NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    is_read           BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_notifications_user ON notifications (user_id);

CREATE TABLE email_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_email VARCHAR(160) NOT NULL,
    subject         VARCHAR(200) NOT NULL,
    body            VARCHAR(2000) NOT NULL,
    status          VARCHAR(12)  NOT NULL,
    error           VARCHAR(300),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE settings (
    setting_key   VARCHAR(80)  PRIMARY KEY,
    setting_value VARCHAR(200) NOT NULL
);
